#!/usr/bin/env node
// build: writes index.html (markup and all of its CSS) from content.js, tools/screens.json (which capture each disk
// shows, and its caption), tools/steps.json and art/meta.json (the sizes the artwork was made at). Run from anywhere:
//   node tools/build.mjs
// Every word on the page comes from content.js; nothing is typed into the HTML by hand.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = p => readFileSync(join(here, p), "utf8");
const ctx = { window: {} };
vm.runInNewContext(read("content.js"), ctx);
const SITE = ctx.window.SITE;
// tools/screens.json: per disk, the captures its screens show ({ shot, caption }); "sheet" is the start screen's contact
// sheet: four captures, each a way to its disk and to that screen of it ([disk, shot, caption]).
const SCREENS = JSON.parse(read("tools/screens.json"));
const made = new Set(readdirSync(join(here, "art/screens")).map(f => f.replace(/-[gt]\d+@\dx\.webp$/, "")));   // the captures there are pictures of
const have = shot => made.has(shot);
const shotsOf = id => (SCREENS[id] ?? []).filter(x => have(x.shot) || console.warn(`no capture ${x.shot}: left out`));
const steps = JSON.parse(read("tools/steps.json"));
const meta = JSON.parse(read("art/meta.json"));
const faceMeta = JSON.parse(read("art/face/meta.json"));   // what is where in the figure's sheets
const edges = JSON.parse(read("art/edges.json"));   // the casing's real top and foot inside the picture's box
// escaped for HTML, with the typewriter apostrophe set as a real one
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/(\w)'(\w)/g, "$1\u2019$2");
// running text: the same words, with hyphenated compounds kept on one line ("64-part", "UTM-to-signup")
const run = s => esc(s).replace(/[A-Za-z0-9:]+(?:-[A-Za-z0-9:]+)+/g, m => `<span class="nb">${m}</span>`)
  .replace(/\{redacted\}/g, '<span class="redact"><span>a title not yet announced</span></span>');
const P = SITE.person;

// What each disk looks like. Shell and label stripe are two of the four inks.
const LOOK = {
  start: ["putty", "slate"], slopcop: ["slate", "red"], anticlassic: ["sky", "putty"],
  revojam: ["putty", "sky"], loanscout: ["slate", "sky"], filestride: ["sky", "slate"], side: ["putty", "red"],
};
const THUMBS = (SCREENS.sheet ?? []).filter(t => have(t[1]));
// A disk's edge as it shows in the drive's slot: its shell, and the label's spine in the stripe ink.
const INKS = { slate: "#2b343b", putty: "#cbc0aa", sky: "#3f7fc4", red: "#d52a26" };
const STRIPE = { slate: "#16222a", putty: "#cbc0aa", sky: "#5da7e9", red: "#d52a26" };

// ---------------------------------------------------------------- steps.css
const img = (name, scales) => {
  const set = scales.map(s => `url("art/${name}@${s}x.webp") ${s}x`).join(", ");
  return `image-set(${set})`;
};
let css = "/* Generated by tools/build.mjs from tools/steps.json and art/meta.json. Do not edit. */\n";
// a variable one step sets and another does not must not leak from the smaller step into the larger
const allVars = [...new Set(steps.flatMap(st => Object.keys(st.vars ?? {})))];
const clouds = ["bank-d", "bank-s", "bank-p", "cloud-a-d", "cloud-b-d", "cloud-a-s"];   // one file each, whatever the screen
css += `:root{--grain:${img("grain", [1, 2, 3])};--grain-w:${meta.grain.w}px;${clouds.map(k => `--${k}:url("art/${meta[k].file}.webp");--${k}-w:${meta[k].w}px;--${k}-h:${meta[k].h}px`).join(";")}}\n`;
for (const st of steps) {
  const m = meta[`pc-${st.pc}`], d = meta[`disk-${st.disk}`], v = meta[`view-${st.pc}`];
  const vars = {
    ...Object.fromEntries(allVars.map(k => [k, "initial"])),
    "--pc-w": `${m.w}px`, "--pc-h": `${m.h}px`, "--pc-pad": `${m.pad}px`, "--pc-top": `${edges[`pc-${st.pc}`].top}px`, "--pc-foot": `${edges[`pc-${st.pc}`].foot}px`,
    "--glass-x": `${m.glass[0]}px`, "--glass-y": `${m.glass[1]}px`, "--glass-w": `${m.glass[2] - m.glass[0]}px`, "--glass-h": `${m.glass[3] - m.glass[1]}px`,
    "--lamp-x": `${m.lamp[0]}px`, "--lamp-y": `${m.lamp[1]}px`, "--lamp-w": `${m.lamp[2] - m.lamp[0]}px`,
    "--slot-x": `${m.slot[0]}px`, "--slot-y": `${((m.slot[1] + m.slot[3]) / 2).toFixed(2)}px`, "--slot-w": `${(m.slot[2] - m.slot[0]).toFixed(2)}px`, "--slot-h": `${(m.slot[3] - m.slot[1]).toFixed(2)}px`,
    "--disk-w": `${d.w}px`, "--disk-h": `${d.h}px`, "--disk-pad": `${d.pad}px`,
    "--view-w": `${v.w}px`, "--view-h": `${v.h}px`, "--bar": `${v.bar}px`, "--shot-x": `${v.shot[0]}px`, "--shot-y": `${v.shot[1]}px`,
    "--thumb-w": `${v.thumb[0]}px`, "--thumb-h": `${v.thumb[1]}px`, "--thumb-gap": `${v.thumb_gap}px`, "--thumb-cap": `${v.thumb_cap}px`, "--thumb-pad": `${v.thumb_pad}px`,
    "--pc-img": img(`pc-${st.pc}`, st.scales), "--glass-img": img(`glass-${st.pc}`, st.scales), "--lamp-img": img(`lamp-${st.pc}`, st.scales),
    ...Object.fromEntries(["slate", "putty", "sky"].map(k => [`--disk-${k}`, img(`disk-${k}-${st.disk}`, st.scales)])),
    ...Object.fromEntries(THUMBS.map(([, id], i) => [`--thumb-${i}`, img(`screens/${id}-t${v.thumb[0]}`, st.scales)])),
    ...(st.vars ?? {}),
  };
  const body = `:root{${Object.entries(vars).map(([k, val]) => `${k}:${val}`).join(";")}}`;
  css += st.media ? `@media ${st.media}{${body}}\n` : `${body}\n`;
}
// Both stylesheets go into the page itself: one request fewer before the first paint. site.css stays the source.
const squeeze = t => t.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s*\n\s*/g, "\n").replace(/\n+/g, "\n").trim();
const inlineCss = squeeze(css) + "\n" + squeeze(read("site.css"));

// ---------------------------------------------------------------- pieces
const links = cls => P.links.map((l, i) =>
  `<a${i === 0 ? ' class="primary"' : ""} href="${esc(l.href)}"${/^https?:/.test(l.href) ? ' rel="noopener"' : ""}>${esc(l.label)}</a>`).join("");

// a long label keeps its first word where the label is narrow (the rest stays for screen readers)
const twoLine = t => t.includes(" / ") || (t.length > 14 && t.includes(" "));
const name = t => t.includes(" / ") ? `${esc(t.split(" / ")[0])}<span class="l2"> /<br>${esc(t.split(" / ")[1])}</span>`
  : t.length > 14 && t.includes(" ") ? `${esc(t.slice(0, t.indexOf(" ")))}<span class="l2"> <br class="brk">${esc(t.slice(t.indexOf(" ") + 1))}</span>`   // two lines, or one where the label is wide enough
  : t.length > 11 && t.includes(" ") ? esc(t).replace(" ", ' <br class="nl">') : esc(t);

const figureRows = figs => figs.map(f => `<div><dt>${esc(f.value)}</dt><dd>${run(f.label)}</dd></div>`).join("");

function screensFor(disk) {
  if (disk.kind === "intro") {
    // the figure: drawn by site.js on the canvas. Its balloon, a card's two lines of words and its sleep are set over it
    const cards = Object.fromEntries(SITE.disks.filter(d => d.kind !== "intro").map(d => [d.id, [d.label, d.tease || ""]]));
    const out = [`<div class="screen face" data-caption="${esc(P.name)}" data-greet="${esc(P.greet || "")}" data-cards="${esc(JSON.stringify(cards))}"><canvas role="img" aria-label="${esc(P.name)}, drawn by the page" data-sheet="${esc(JSON.stringify(faceMeta))}"></canvas><p class="say" aria-hidden="true" hidden><span></span><span></span></p><p class="card-t" aria-hidden="true" hidden></p><p class="card-h" aria-hidden="true" hidden></p><p class="zz" aria-hidden="true" hidden><i>z</i><i>z</i><i>z</i></p></div>`];
    if (THUMBS.length === 4) out.push(`<div class="screen type splash" data-caption="${esc(disk.label)}">
<p class="t-work">${THUMBS.map(([d, shot, cap], i) => `<a href="#${d}" data-screen="${shotsOf(d).findIndex(x => x.shot === shot)}"><i style="background-image:var(--thumb-${i})"></i><b>${esc(cap)}</b></a>`).join("")}</p>
</div>`);
    return out;
  }
  // a screen with a clip: the capture is the clip's first frame, and site.js lays the clip over it when the screen shows
  const out = shotsOf(disk.id).map(x => `<figure class="screen shot" data-shot="${esc(x.shot)}"${x.clip ? ` data-clip="${esc(x.clip)}" data-sizes="${(x.sizes ?? [512, 896]).join(" ")}"` : ""} data-caption="${esc(x.caption)}"><img alt="${esc(x.caption)}" decoding="async" draggable="false">${x.clip ? '<video muted loop playsinline preload="none" disablepictureinpicture disableremoteplayback tabindex="-1" aria-hidden="true"></video>' : ""}</figure>`);
  if (!out.length) out.push(typeScreen(disk));
  return out;
}

function typeScreen(disk) {
  const body = disk.figures.length
    ? `<dl class="t-figs n${disk.figures.length}">${figureRows(disk.figures)}</dl>`
    : `<p class="t-name">${esc(disk.title)}</p><p class="t-line">${esc(disk.role)}</p><p class="t-meta"><span>${esc(disk.dates)}</span><span>${esc((disk.stack ?? []).join(", "))}</span></p>`;
  return `<div class="screen type readout" data-caption="${esc(disk.caption ?? disk.title)}">${body}</div>`;
}

// A title's first letter decides how far its ink sits from its box (stems .043 em, round and pointed letters .022).
// A two-company title is two pieces, each with its own: where it runs to two lines, both lines' ink starts on the text's edge.
const lsb = t => /^[BDEFHIKLMNPRU]/i.test(t) ? ".043" : ".022";
function heading(t) {
  if (!t.includes(" / ")) return `<h2 style="--lsb:${lsb(t)}">${esc(t)}</h2>`;
  const [a, b] = t.split(" / ");
  return `<h2 class="two" style="--lsb:${lsb(a)}"><span>${esc(a)} /</span> <span style="--lsb2:${lsb(b)}">${esc(b)}</span></h2>`;
}

// Every panel is its title and one or two lists of rows, and a row is the same parts wherever it stands: a key, its
// words, and (in the start panel's list of disks) a figure at the line's end. One set of rules draws them all: the last section of site.css.
const kv = p => { const i = p.indexOf(": "); return [p.slice(0, i), p.slice(i + 2)]; };   // "Key: words"
const row = (k, v, cls = "") => `<div class="row${cls}" data-u><dt class="k">${esc(k)}</dt><dd class="v">${v}</dd></div>`;
const rows = {
  skills: disk => `<dl class="rows skills">${disk.points.map(p => { const [k, v] = kv(p); return row(k, run(v)); }).join("")}</dl>`,
  // a disk's row: its title, its post (up to any colon or bracket: the rest is in its chapter), the years on its label
  jobs: () => `<ol class="rows jobs">${SITE.disks.filter(d => d.kind !== "intro").map(d => `<li data-u><a class="row" href="#${d.id}"><b class="k">${esc(d.title)}</b><span class="v">${esc(d.role.split(/[:(]/)[0].trim())}</span><time class="t">${esc(d.sub.split(" · ").pop())}</time></a></li>`).join("")}</ol>`,
  // a disk's own panel: its post and dates (a bracket after the post, "(contract)", is said ahead of the dates),
  // what the place is (an aside: it gives way first on a short page), what was built, the stack
  facts: disk => `<dl class="rows facts">${[
    (([, post, note]) => row(post, `${note ? esc(note[0].toUpperCase() + note.slice(1)) + ", " : ""}<span class="nb">${esc(disk.dates)}</span>`))(/^(.*?)(?:\s*\((.+)\))?$/.exec(disk.role.split(":")[0].trim())),
    disk.about ? row(kv(disk.about)[0], run(kv(disk.about)[1]), " aside") : "",
    ...disk.points.map(p => { const [k, v] = kv(p); return row(k, run(v)); }),
    disk.stack ? row("Stack", esc(disk.stack.join(", "))) : "",
  ].join("")}</dl>`,
  // its figures, each keyed by its number. A disk whose screen is its figures does not say them twice.
  nums: disk => disk.figures.length && shotsOf(disk.id).length ? `<dl class="rows nums">${disk.figures.map(f => row(f.value, run(f.label))).join("")}</dl>` : "",
};

// the way back to the start disk, above a chapter's title. The start panel has none to offer, and keeps its room
// (the same words, unseen), so every panel's title stands at one height.
const backMark = `<svg viewBox="0 0 12 10" aria-hidden="true"><path d="M5 1 1 5l4 4M1 5h11"/></svg><span>${esc(SITE.disks[0].label)}</span>`;
function chapter(disk, n) {
  const arrow = d => `<svg viewBox="0 0 8 10" aria-hidden="true"><path d="${d}"/></svg>`;
  const folio = `<p class="folio" hidden><button type="button" class="pg-prev" aria-label="Previous page">${arrow("M7 0v10L1 5z")}</button><span class="pg-count" aria-live="polite"></span><button type="button" class="pg-next" aria-label="Next page">${arrow("M1 0v10l6-5z")}</button></p>`;
  const intro = disk.kind === "intro";
  return `<article class="chapter${intro ? " intro" : ""}" id="m-${disk.id}" data-for="${disk.id}"${n ? ` style="--n:${n}"` : ""}>
<header>
${intro ? `<span class="back is-none" aria-hidden="true">${backMark}</span>` : `<a class="back" href="#${SITE.disks[0].id}">${backMark}</a>`}
${heading(disk.title)}
</header>
<div class="body">
${intro ? rows.skills(disk) : rows.facts(disk)}
${intro ? rows.jobs() : rows.nums(disk)}
</div>
${folio}
</article>`;
}

const diskButton = (disk, i) => {
  const [shell, stripe] = LOOK[disk.id];
  const parts = disk.sub.split(" · ");
  const short = disk.kind === "intro" ? "" : parts[parts.length - 1];
  return `<button class="disk" type="button" data-disk="${disk.id}" data-shell="${shell}" data-stripe="${stripe}"${twoLine(disk.label) ? ' data-lines="2"' : ""} aria-pressed="${i === 0}">
<span class="disk-fly"><span class="disk-body"><span class="label"><span class="label-name">${name(disk.label)}</span><span class="label-sub">${esc(disk.kind === "intro" ? disk.sub : disk.sub.replace(" · ", ", "))}</span><span class="label-short">${esc(short)}</span><span class="label-lines"></span></span></span><span class="disk-rim"></span><span class="disk-shade"><span class="disk-dip"></span></span></span>
</button>`;
};

const ids = SITE.disks.map(d => d.id);
// Where each disk lies. Each disk but the first has its own place (six, with seven disks), and the first ("Start here") lies in the
// place of whichever disk is in the drive. After that site.js only ever swaps two disks.
// k is a place; in the rack of label ends that is a row and a column (three across under the machine on the
// narrower layouts; two across beside it on the wide one).
const place = k => `--k:${k};--row:${k < 3 ? 0 : 1};--col:${k % 3};--drow:${Math.floor(k / 2)};--dcol:${k % 2}`;
const stateCss = [
  ids.map((id, j) => `.disk:nth-child(${j + 1}){${place(Math.max(0, j - 1))}}`).join(""),
  ...ids.map((id, x) => {
    const w = x === 0 ? `html:not([data-wanted])` : null, sel = `html[data-wanted="${id}"]`;
    const d = x === 0 ? `html:not([data-disk])` : null, dsel = `html[data-disk="${id}"]`;
    const both = (a, b, rest) => [a, b].filter(Boolean).map(p => `${p} ${rest}`).join(",");
    return (x > 0 ? `${sel} .disk:nth-child(1){${place(x - 1)}}` : "") +
      `${sel} #m-${id}{display:flex}${dsel} .screens[data-for="${id}"]{display:block}` +
      `${both(d, dsel, ".edge")}{--shell-c:${INKS[LOOK[id][0]]};--stripe-c:${STRIPE[LOOK[id][1]]}}` +
      `${both(w, sel, `.disk[data-disk="${id}"]:not(.is-flying) .disk-fly`)}{opacity:0}` +
      `${both(w, sel, `.disk[data-disk="${id}"]:not(.is-flying)`)}{pointer-events:none}`;
  }),
].join("\n");

// The machine's picture is the largest paint. It is preloaded for the phone steps, where the budget is tight.
const preloads = steps.map((st, i) => {
  if (st.layout !== "p") return "";
  // a step's own media, and none of the later steps' (in the stylesheet the later rule wins)
  const later = steps.slice(i + 1).map(x => `(not (${x.media}))`);
  const media = [st.media, ...later].filter(Boolean).join(" and ");
  const set = st.scales.map(s => `art/pc-${st.pc}@${s}x.webp ${s}x`).join(", ");
  return `<link rel="preload" as="image" fetchpriority="high" imagesrcset="${set}" href="art/pc-${st.pc}@${st.scales[0]}x.webp" media="${media}">`;
});

let n = 0;
const html = `<!doctype html>
<html lang="en" class="no-js">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(P.name)}: ${esc(SITE.disks[0].role.toLowerCase())}</title>
<meta name="description" content="${esc(P.line)}">
<meta name="theme-color" content="#4f9be5">
<link rel="icon" href="favicon/favicon.ico" sizes="any">
<link rel="icon" type="image/png" sizes="32x32" href="favicon/favicon-32x32.png">
<link rel="apple-touch-icon" sizes="180x180" href="favicon/apple-touch-icon.png"><script>(function(d){var h=location.hash.slice(1);d.className="js";d.dataset.disk=d.dataset.wanted=${JSON.stringify(ids)}.indexOf(h)>0?h:"start"})(document.documentElement)</script>
<link rel="preload" as="font" type="font/woff2" href="fonts/tanker.woff2" crossorigin>
<link rel="preload" as="font" type="font/woff2" href="fonts/apfel-regular.woff2" crossorigin>
<link rel="preload" as="font" type="font/woff2" href="fonts/apfel-fett.woff2" crossorigin>
<link rel="preload" as="font" type="font/woff2" href="fonts/apfel-mittel.woff2" crossorigin>
${preloads.filter(Boolean).join("\n")}
<style>
${inlineCss}
${stateCss}
</style>
</head>
<body>
<main class="box">
<header class="id">
<h1>${esc(P.name)}</h1>
<p class="line">${esc(P.line)}</p>
<nav class="links" aria-label="Contact">${links()}</nav>
</header>
<div class="stage">
<nav class="disks" aria-label="Disks">
${SITE.disks.map(diskButton).join("\n")}
</nav>
<div class="pc">
<div class="tube">
<div class="view">
${SITE.disks.map(d => `<div class="screens" data-for="${d.id}">\n${screensFor(d).map((s, i) => i === 0 ? s.replace('class="screen', 'class="screen is-on') : s).join("\n")}\n</div>`).join("\n")}
<div class="sweep"></div>
<div class="shade"></div>
<div class="bar"><span class="cap">${esc(SITE.disks[0].label)}</span><span class="pager" hidden><button type="button" class="prev" aria-label="Previous screen"><svg viewBox="0 0 8 10" aria-hidden="true"><path d="M7 0v10L1 5z"/></svg></button><span class="count" aria-live="polite"></span><button type="button" class="next" aria-label="Next screen"><svg viewBox="0 0 8 10" aria-hidden="true"><path d="M1 0v10l6-5z"/></svg></button></span></div>
</div>
<div class="crt"></div>
<p class="nosignal" aria-hidden="true">No signal</p>
</div>
<div class="pc-art"></div>
<div class="glass"></div>
<div class="lamp"></div>
<div class="edge"></div>
<div class="ring"></div>
<i class="led led-crt"></i><i class="led led-box"></i>
<button type="button" class="power power-crt" aria-label="Monitor power" aria-pressed="true"></button>
<button type="button" class="power power-box" aria-label="Computer power" aria-pressed="true"></button>
<button type="button" class="eject" aria-label="Eject the disk: back to ${esc(SITE.disks[0].label)}"></button>
</div>
</div>
<section class="manual" aria-label="User's guide">
${SITE.disks.map(d => chapter(d, d.kind === "intro" ? 0 : ++n)).join("\n")}
</section>
</main>
<i class="tint tint-top" aria-hidden="true"></i><i class="tint tint-foot" aria-hidden="true"></i>
<script src="site.min.js" defer></script>
</body>
</html>
`;
writeFileSync(join(here, "index.html"), html);
// site.js is the source; the page loads it without its comments and indentation
const js = read("site.js").replace(/\/\*[\s\S]*?\*\//g, "").split("\n").map(l => l.replace(/\s{2,}\/\/ .*$/, "").replace(/^\s*\/\/ .*$/, "").trim()).filter(Boolean).join("\n");
writeFileSync(join(here, "site.min.js"), js + "\n");
console.log(`index.html ${(html.length / 1024).toFixed(1)} KB`);
